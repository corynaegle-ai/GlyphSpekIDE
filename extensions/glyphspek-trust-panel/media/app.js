/**
 * TWO-TIER TRUST MODEL (sweep-06 High fix).
 *
 * The committed demo key MUST NOT confer PRODUCT authority — anyone with repo
 * access holds the matching demo PRIVATE key (prototypes/trust-panel/keys/
 * demo-verifier-private.pem) and could otherwise sign a fully-AUTHORITATIVE
 * bundle. So trust is split into two cryptographically-distinct tiers:
 *
 *   PRODUCT tier — keys provisioned OUT-OF-BAND ONLY, via the host:
 *     window.GLYPHSPEK_TRUSTED_VERIFIER_KEYS = ['<PEM or base64 SPKI>', ...]
 *     (in the VS Code extension this is the `glyphspek.trustedVerifierKeys`
 *     setting / operator keystore). A PRODUCT-tier match is the ONLY thing that
 *     can make a verdict FULLY AUTHORITATIVE. The built-in demo key is NOT here.
 *
 *   DEMO tier — the built-in DEMO_VERIFIER_PUBLIC_KEY_PEM ONLY. A DEMO-tier
 *     match yields the separate, clearly-labeled DEMO-AUTHORITATIVE state so the
 *     committed sample still demonstrates the gate, but it can NEVER be presented
 *     as production AUTHORITATIVE.
 *
 * A bundle's embedded verifierPublicKey is intentionally in NEITHER tier; it is
 * consulted last, only to label the "untrusted-key" state for honest reporting.
 */

/** The built-in DEMO tier: the committed demo key, and nothing else. */
const DEMO_VERIFIER_KEYS = [DEMO_VERIFIER_PUBLIC_KEY_PEM];

/**
 * Out-of-band seam: classify trusted keys into the two tiers. Reads the global
 * the embedder may define BEFORE app.js loads:
 *   window.GLYPHSPEK_TRUSTED_VERIFIER_KEYS = ['<PEM or base64 SPKI>', ...]
 * Those injected keys are PRODUCT tier. The built-in demo key is DEMO tier and
 * is NEVER silently folded into the product set. NEVER reads the bundle.
 *
 * Returns { productKeys, demoKeys } — each a de-duped array of key texts. A key
 * is de-duped by normalized DER id; if the SAME key is both injected (product)
 * and the built-in demo key, PRODUCT wins (it is removed from demoKeys) so an
 * operator who deliberately provisions that key out-of-band gets product trust,
 * while the built-in copy alone stays demo-only.
 *
 * Uses function declarations (publicKeyToDer / bytesToHex below) that are
 * hoisted, so the forward reference is safe at call time.
 */
function getTrustedVerifierKeys() {
  const injected =
    (typeof window !== 'undefined' && Array.isArray(window.GLYPHSPEK_TRUSTED_VERIFIER_KEYS))
      ? window.GLYPHSPEK_TRUSTED_VERIFIER_KEYS
      : [];

  // De-dupe each tier by normalized DER id. Malformed entries are skipped, not
  // fatal. `productIds` lets us keep a product key out of the demo tier.
  const productIds = new Set();
  const productKeys = [];
  for (const k of injected) {
    if (typeof k !== 'string' || !k.trim()) continue;
    let id;
    try { id = keyDerId(k); } catch (_) { continue; }
    if (productIds.has(id)) continue;
    productIds.add(id);
    productKeys.push(k);
  }

  const demoIds = new Set();
  const demoKeys = [];
  for (const k of DEMO_VERIFIER_KEYS) {
    if (typeof k !== 'string' || !k.trim()) continue;
    let id;
    try { id = keyDerId(k); } catch (_) { continue; }
    if (productIds.has(id) || demoIds.has(id)) continue; // product wins
    demoIds.add(id);
    demoKeys.push(k);
  }

  return { productKeys, demoKeys };
}

/** Normalize a key's SPKI body to a stable id (hex of DER) for de-dupe. */
function keyDerId(keyText) {
  // publicKeyToDer / bytesToHex are declared below; this helper is only called
  // after parse, by which point both hoisted declarations are bound.
  return bytesToHex(publicKeyToDer(keyText));
}

/**
 * Canonical JSON with stable (lexicographically sorted) keys at every level,
 * compact, UTF-8. Direct port of spikes/p0-trace/canonical-json.ts — it MUST
 * match byte-for-byte or signatures will not verify.
 */
function canonicalJson(obj) {
  return canonicalEncode(obj);
}

function canonicalEncode(value) {
  if (value === null) return 'null';
  const t = typeof value;
  if (t === 'string') return JSON.stringify(value);
  if (t === 'number') return Number.isFinite(value) ? String(value) : 'null';
  if (t === 'boolean') return value ? 'true' : 'false';
  if (Array.isArray(value)) {
    const parts = value.map((item) => (item === undefined ? 'null' : canonicalEncode(item)));
    return '[' + parts.join(',') + ']';
  }
  if (t === 'object') {
    const keys = Object.keys(value).sort();
    const parts = [];
    for (const key of keys) {
      const v = value[key];
      if (v === undefined) continue; // omit undefined, matching JSON.stringify
      parts.push(JSON.stringify(key) + ':' + canonicalEncode(v));
    }
    return '{' + parts.join(',') + '}';
  }
  if (t === 'bigint') throw new TypeError('Do not know how to serialize a BigInt');
  return 'undefined';
}

/**
 * Build the exact canonical message bytes that were signed: strip the verdict's
 * own `signature` field, then canonicalize { traceRootHash, verdict }.
 */
function verdictMessageBytes(verdict) {
  const core = {};
  for (const k of Object.keys(verdict)) {
    if (k === 'signature') continue;
    core[k] = verdict[k];
  }
  const json = canonicalJson({ traceRootHash: core.traceRootHash, verdict: core });
  return new TextEncoder().encode(json);
}

/** Decode a base64 string to a Uint8Array. Throws on malformed input. */
function base64ToBytes(b64) {
  const clean = String(b64).replace(/\s+/g, '');
  const bin = atob(clean); // throws on invalid base64
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

/**
 * Normalize a verifier public key supplied as SPKI PEM or bare base64 SPKI to
 * DER bytes (Uint8Array) for crypto.subtle.importKey('spki', ...).
 */
function publicKeyToDer(keyText) {
  const text = String(keyText).trim();
  const body = text
    .replace(/-----BEGIN [^-]+-----/g, '')
    .replace(/-----END [^-]+-----/g, '')
    .replace(/\s+/g, '');
  return base64ToBytes(body);
}

/** True iff this environment exposes Web Crypto subtle (needed for verify). */
function hasWebCryptoSubtle() {
  return typeof crypto !== 'undefined' && crypto && typeof crypto.subtle !== 'undefined';
}

/**
 * Verify a VerifierVerdict's Ed25519 signature. Tries the TRUSTED (out-of-band)
 * key set FIRST; only a trusted-key match can make a verdict authoritative.
 * Keys are tried by TIER (see getTrustedVerifierKeys): PRODUCT first, then DEMO,
 * then — only to label the untrusted state — the BUNDLE-supplied key.
 *
 * Returns (never throws):
 *   { status, detail, trusted, tier }
 * where status ∈ 'verified' | 'failed' | 'no-signature' | 'no-key'
 *               | 'unsupported' | 'error'
 *   tier ∈ 'product'        -> verified by an out-of-band PRODUCT key (FULL auth)
 *        | 'demo'           -> verified by the built-in DEMO key (DEMO-AUTH only)
 *        | 'untrusted-key'  -> verified only by the BUNDLE-supplied key
 *        | null             -> no valid signature
 *   trusted: true  -> tier is 'product' OR 'demo' (a pinned trust root matched);
 *                     the GATE still branches on tier — only 'product' is FULLY
 *                     authoritative, 'demo' is DEMO-AUTHORITATIVE.
 *   trusted: false -> only the BUNDLE key verified it, or nothing did.
 * status==='verified' && tier==='product' is the ONLY full-authoritative case.
 */
async function verifyVerdictSignature(verdict, bundlePublicKeyText) {
  const sig = verdict && verdict.signature;
  if (!sig || typeof sig.value !== 'string') {
    return { status: 'no-signature', detail: 'verdict carries no signature', trusted: false, tier: null };
  }
  if (sig.alg !== 'ed25519') {
    return { status: 'failed', detail: 'unsupported signature alg: ' + sig.alg, trusted: false, tier: null };
  }
  if (!hasWebCryptoSubtle()) {
    return { status: 'unsupported', detail: 'Web Crypto (crypto.subtle) unavailable', trusted: false, tier: null };
  }

  let sigBytes;
  try { sigBytes = base64ToBytes(sig.value); }
  catch (err) { return { status: 'error', detail: 'malformed signature: ' + err.message, trusted: false, tier: null }; }

  const msg = verdictMessageBytes(verdict);

  const { productKeys, demoKeys } = getTrustedVerifierKeys();

  // (A) PRODUCT tier first. Any one that verifies => FULLY authoritative-eligible.
  for (const keyText of productKeys) {
    const ok = await verifyWithKey(keyText, sigBytes, msg);
    if (ok === 'unsupported') {
      return { status: 'unsupported', detail: 'this browser lacks Web Crypto Ed25519 support', trusted: false, tier: null };
    }
    if (ok === true) {
      return { status: 'verified', detail: 'Ed25519 signature valid for a TRUSTED (out-of-band) PRODUCT verifier key', trusted: true, tier: 'product' };
    }
  }

  // (B) DEMO tier next. A pass here is the built-in demo trust root only — it can
  //     reach DEMO-AUTHORITATIVE but is NEVER full product authoritative.
  for (const keyText of demoKeys) {
    const ok = await verifyWithKey(keyText, sigBytes, msg);
    if (ok === 'unsupported') {
      return { status: 'unsupported', detail: 'this browser lacks Web Crypto Ed25519 support', trusted: false, tier: null };
    }
    if (ok === true) {
      return { status: 'verified', detail: 'Ed25519 signature valid for the built-in DEMO verifier key — NOT a production trust root', trusted: true, tier: 'demo' };
    }
  }

  // (C) Bundle-supplied key, ONLY to label "valid but untrusted". A pass here is
  //     NOT authoritative — the key came from the (untrusted) bundle.
  if (bundlePublicKeyText) {
    const ok = await verifyWithKey(bundlePublicKeyText, sigBytes, msg);
    if (ok === true) {
      return {
        status: 'verified',
        detail: 'signature valid, but only for a key SUPPLIED BY THE BUNDLE — not a trusted out-of-band key',
        trusted: false,
        tier: 'untrusted-key',
      };
    }
  }

  if (productKeys.length === 0 && demoKeys.length === 0 && !bundlePublicKeyText) {
    return { status: 'no-key', detail: 'no trusted verifier key available', trusted: false, tier: null };
  }
  return { status: 'failed', detail: 'signature does NOT verify against any trusted or bundle key', trusted: false, tier: null };
}

/** Import one SPKI key and verify; returns true|false|'unsupported'. Never throws. */
async function verifyWithKey(keyText, sigBytes, msg) {
  let der, key;
  try { der = publicKeyToDer(keyText); }
  catch (_) { return false; }
  try {
    key = await crypto.subtle.importKey('spki', der, { name: 'Ed25519' }, false, ['verify']);
  } catch (_) {
    return 'unsupported';
  }
  try {
    return await crypto.subtle.verify({ name: 'Ed25519' }, key, sigBytes, msg);
  } catch (_) {
    return false;
  }
}

/* ================================================================== *
 * TRACE-CHAIN VERIFICATION (evidence-bundle integrity gate).
 *
 * A valid signature only proves the verdict OBJECT is authentic. It does NOT
 * prove the loaded trace is the one the verdict committed to. So before
 * presenting a verdict as AUTHORITATIVE we ALSO verify, in-browser:
 *   1. verifyChainBrowser(events).ok            — the hash chain is intact, and
 *   2. computeTraceRootBrowser(events) === verdict.traceRootHash — the loaded
 *      trace is exactly the one the verdict signed over.
 *
 * The hashing is reproduced BYTE-FOR-BYTE from spikes/p0-trace/trace-store.ts:
 *
 *   hash_n = sha256( prevHash_n + canonicalJson({v,runId,seq,ts,type,payload[,source]}) )
 *
 * — genesis prevHash is 64 hex zeros; `source` is folded into the hashed
 * content ONLY when present (source-less events hash exactly as before that
 * field existed); the trace root is simply the hash of the LAST event (GENESIS
 * for an empty trace), since each hash already commits to all prior history.
 * canonicalJson above is the same byte-exact port the signature path uses.
 * ================================================================== */

/** Genesis prevHash for the first event in a chain: 64 hex zeros. */
const GENESIS_HASH = '0'.repeat(64);

/**
 * The canonical content over which an event's hash is computed. EXCLUDES the
 * derived chain fields (prevHash, hash). `source` is included ONLY when present,
 * matching spikes/p0-trace/trace-store.ts hashableContent() exactly.
 */
function hashableContent(evt) {
  const content = {
    v: evt.v,
    runId: evt.runId,
    seq: evt.seq,
    ts: evt.ts,
    type: evt.type,
    payload: evt.payload,
  };
  if (evt.source !== undefined) content.source = evt.source;
  return content;
}

/** Hex-encode a buffer/Uint8Array as lowercase hex. */
function bytesToHex(buf) {
  const bytes = new Uint8Array(buf);
  let out = '';
  for (let i = 0; i < bytes.length; i++) {
    out += bytes[i].toString(16).padStart(2, '0');
  }
  return out;
}

/** sha256(prevHash + canonicalJson(content)) as lowercase hex (async, Web Crypto). */
async function computeEventHash(prevHash, evt) {
  const msg = new TextEncoder().encode(prevHash + canonicalJson(hashableContent(evt)));
  const digest = await crypto.subtle.digest('SHA-256', msg);
  return bytesToHex(digest);
}

/**
 * Recompute every event's hash and verify linkage, mirroring
 * spikes/p0-trace/trace-store.ts verifyChain(). Returns { ok, brokenIndex }.
 * For each event i: expected prevHash is GENESIS_HASH for i===0 else
 * events[i-1].hash, and the recomputed hash must equal the stored hash.
 * Returns { ok:false } with no brokenIndex if Web Crypto is unavailable.
 */
async function verifyChainBrowser(events) {
  if (!hasWebCryptoSubtle()) return { ok: false };
  const list = Array.isArray(events) ? events : [];
  let expectedPrev = GENESIS_HASH;
  for (let i = 0; i < list.length; i++) {
    const evt = list[i];
    if (evt.prevHash !== expectedPrev) return { ok: false, brokenIndex: i };
    const recomputed = await computeEventHash(evt.prevHash, evt);
    if (recomputed !== evt.hash) return { ok: false, brokenIndex: i };
    expectedPrev = evt.hash;
  }
  return { ok: true };
}

/**
 * Compute the trace root over an ordered event list: the hash of the LAST
 * event, or GENESIS_HASH for an empty trace. Mirrors computeTraceRoot() in
 * spikes/p0-trace/trace-store.ts. (Returns the stored last-event hash; pair
 * with verifyChainBrowser to confirm that stored hash is itself authentic.)
 */
function computeTraceRootBrowser(events) {
  const list = Array.isArray(events) ? events : [];
  if (list.length === 0) return GENESIS_HASH;
  return list[list.length - 1].hash;
}

