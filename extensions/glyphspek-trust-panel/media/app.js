/**
 * Parse one .json / .jsonl text blob into { events, claims, verifierPublicKey }.
 * Accepts:
 *   - a JSON array of TraceEvent envelopes,
 *   - JSONL (one TraceEvent per line),
 *   - a single TraceEvent object,
 *   - a wrapper { events:[...], claims:{...}, verifierPublicKey:"<PEM|base64>" }.
 * `verifierPublicKey` / `claims` are optional; absent fields stay null so we
 * never silently borrow them from another source on a trust surface.
 */
function parseTraceText(text) {
  const trimmed = text.trim();
  if (!trimmed) throw new Error('empty file');
  let events = null;
  let claims = null;
  let verifierPublicKey = null;

  // JSONL detection FIRST: a real trace.jsonl (one TraceEvent per line) has
  // multiple lines each starting with `{`. We must not try to JSON.parse the
  // whole file as a single object in that case.
  const lines = trimmed.split('\n').map((l) => l.trim()).filter(Boolean);
  const looksLikeJsonl =
    lines.length > 1 && lines.every((l) => l[0] === '{') && trimmed[0] !== '[';

  if (looksLikeJsonl) {
    events = lines.map((line, i) => {
      try {
        return JSON.parse(line);
      } catch (err) {
        throw new Error('JSONL parse error on line ' + (i + 1) + ': ' + err.message);
      }
    });
  } else if (trimmed[0] === '[') {
    events = JSON.parse(trimmed);
  } else if (trimmed[0] === '{') {
    const obj = JSON.parse(trimmed);
    if (Array.isArray(obj)) {
      events = obj;
    } else if (Array.isArray(obj.events)) {
      events = obj.events;
      claims = obj.claims || null;
      verifierPublicKey = obj.verifierPublicKey || obj.verifierPublicKeyPem || null;
    } else if (obj.type) {
      events = [obj]; // single event object
    } else {
      throw new Error('unrecognized JSON object: expected { events: [...] } or a JSON array');
    }
  } else {
    // Single-line JSONL fallback.
    events = lines.map((line) => JSON.parse(line));
  }
  if (!Array.isArray(events) || !events.length) throw new Error('no events found');
  return { events, claims, verifierPublicKey };
}

/** Heuristic: does this text look like a PEM / bare-base64 public key? */
function looksLikePublicKey(text) {
  const t = String(text).trim();
  if (/-----BEGIN [A-Z ]*PUBLIC KEY-----/.test(t)) return true;
  // Bare base64 SPKI for Ed25519 is short and base64-only on a single logical line.
  return /^[A-Za-z0-9+/=\s]+$/.test(t) && t.replace(/\s+/g, '').length < 200 && t[0] !== '{' && t[0] !== '[';
}

/**
 * Load a parsed bundle into state, then asynchronously verify the verdict
 * signature and re-render. `events` is required; claims/publicKey optional.
 */
function loadBundle(bundle, sourceLabel) {
  state.trace = bundle.events || [];
  state.claims = bundle.claims || null;
  // The bundle-supplied key is the NON-AUTHORITATIVE "case B" fallback only: it
  // can flag a "signed by an untrusted bundle key" state but can NEVER make a
  // verdict authoritative. Trust is decided solely by getTrustedVerifierKeys().
  state.verifierPublicKey = bundle.verifierPublicKey || null;
  // A standalone verdict.json (capstone-style) takes precedence over any
  // verifier_verdict event embedded in the trace.
  state.standaloneVerdict = bundle.verdict || null;
  state.source = sourceLabel;
  state.sigResult = null; // reset; verifySignatureAndRerender fills it in
  state.chainResult = null; // reset; verifySignatureAndRerender fills it in
  renderAll();
  setStatus('Loaded ' + state.trace.length + ' events from ' + sourceLabel + '.', 'ok');
  verifySignatureAndRerender();
}

/**
 * Verify the current trace's verdict signature with Web Crypto, then re-render
 * the verdict panel with the gate result. Idempotent and safe to call repeatedly.
 */
async function verifySignatureAndRerender() {
  const verdict = deriveVerdict(state.trace);
  if (!verdict) {
    state.sigResult = null;
    state.chainResult = null;
    renderVerifierVerdict();
    return;
  }
  // Show the pending state immediately, then resolve.
  state.sigResult = null;
  state.chainResult = null;
  renderVerifierVerdict();

  // (1) signature over the verdict object, and (2) trace-chain + root binding —
  // BOTH are required before a verdict is AUTHORITATIVE. Compute them in
  // parallel; a valid signature over a verdict whose traceRootHash does not
  // match the loaded trace (or whose chain is broken) is NOT authoritative.
  const [sigResult, chainResult] = await Promise.all([
    verifyVerdictSignature(verdict, state.verifierPublicKey),
    verifyTraceIntegrity(state.trace, verdict),
  ]);
  state.sigResult = sigResult;
  state.chainResult = chainResult;
  renderVerifierVerdict();
}

/**
 * Verify the loaded trace's hash chain and bind its root to the verdict.
 * Returns { chainOk, brokenIndex, recomputedRoot, verdictRoot, rootMatches }.
 * `recomputedRoot` is the root computed from the loaded events;
 * `rootMatches` compares it to `verdict.traceRootHash`. NEVER throws.
 */
async function verifyTraceIntegrity(events, verdict) {
  const verdictRoot = (verdict && verdict.traceRootHash) || null;
  let chain;
  try {
    chain = await verifyChainBrowser(events);
  } catch (err) {
    chain = { ok: false };
  }
  const recomputedRoot = computeTraceRootBrowser(events);
  const rootMatches =
    typeof verdictRoot === 'string' &&
    verdictRoot.length > 0 &&
    recomputedRoot === verdictRoot;
  return {
    chainOk: !!chain.ok,
    brokenIndex: chain.brokenIndex,
    recomputedRoot,
    verdictRoot,
    rootMatches,
  };
}

/*
 * Bundle-load size caps (mirrors the extension's MAX_BUNDLE_FILE_BYTES /
 * MAX_BUNDLE_TOTAL_BYTES in extension/src/extension.ts). The panel reads each
 * selected/dropped file fully into memory and then parses/renders it; an
 * incident-scale trace could otherwise freeze the tab. We refuse to READ a file
 * over the per-file cap, or once the running total would exceed the total cap —
 * the embedded-sample path (window.GLYPHSPEK_SAMPLE_BUNDLE) never goes through
 * here, so this only bounds user-supplied files.
 */
const MAX_BUNDLE_FILE_BYTES = 8 * 1024 * 1024;
const MAX_BUNDLE_TOTAL_BYTES = 32 * 1024 * 1024;

/** Human-readable byte size for the size-cap status messages. */
function formatBundleBytes(bytes) {
  if (bytes < 1024) return bytes + ' B';
  const mib = bytes / (1024 * 1024);
  if (mib >= 1) return mib.toFixed(1) + ' MiB';
  return (bytes / 1024).toFixed(1) + ' KiB';
}

/**
 * Handle one or more dropped/picked files as a single run bundle. A bundle is
 * any combination of:
 *   - a trace (.jsonl one-event-per-line, a JSON array of events, or a wrapper
 *     { events, claims, verifierPublicKey }),
 *   - a standalone verdict.json (VerifierVerdict { checks, overallVerdict,
 *     traceRootHash, signature }), and
 *   - a verifier public key (.pem SPKI or bare base64).
 * This matches the capstone output at demo-output/capstone/ (trace.jsonl +
 * verdict.json + verifier-public-key.pem). The public key is resolved
 * out-of-band — it is NOT trusted from inside the trace/actor.
 */
function handleFiles(fileList) {
  const all = Array.prototype.slice.call(fileList || []);
  if (!all.length) return;

  // Size gate BEFORE any read: drop files over the per-file cap, and stop once
  // the running total would exceed the total cap. Bundles are small, so a large
  // file is almost certainly a mistake; we refuse to read it rather than freeze
  // the tab. Friendly, non-fatal status via the existing setStatus mechanism.
  const files = [];
  let runningTotal = 0;
  const skipped = [];
  for (const file of all) {
    const size = typeof file.size === 'number' ? file.size : 0;
    if (size > MAX_BUNDLE_FILE_BYTES) {
      skipped.push(
        'File ' + file.name + ' is too large (' + formatBundleBytes(size) +
          ') — bundles are small; max ' + formatBundleBytes(MAX_BUNDLE_FILE_BYTES) + ' per file',
      );
      continue;
    }
    if (runningTotal + size > MAX_BUNDLE_TOTAL_BYTES) {
      skipped.push(
        'File ' + file.name + ' skipped — bundle exceeds the ' +
          formatBundleBytes(MAX_BUNDLE_TOTAL_BYTES) + ' total limit',
      );
      continue;
    }
    runningTotal += size;
    files.push(file);
  }
  if (!files.length) {
    setStatus(
      skipped.length ? skipped.join('. ') + '.' : 'No readable files selected.',
      'err',
    );
    return;
  }

  let pending = files.length;
  let events = null;
  let claims = null;
  let verifierPublicKey = null;
  let verdict = null;
  const names = [];
  // Seed with any over-cap skips so they surface in the final status even when
  // the remaining (in-cap) files don't yield a trace/verdict.
  const errors = skipped.slice();

  function done() {
    if (pending > 0) return;
    if (!events && !verdict) {
      setStatus(
        'No trace or verdict found in ' +
          (names.join(', ') || 'the selected files') +
          (errors.length ? '. ' + errors.join('; ') : '. Provide a trace .json/.jsonl or verdict.json.'),
        'err',
      );
      return;
    }
    loadBundle({ events: events || [], claims, verifierPublicKey, verdict }, names.join(' + '));
    // If we loaded successfully but dropped some over-cap files, append a notice
    // (loadBundle just set the "Loaded …" status; keep that, add the skip note).
    if (skipped.length) setStatus('Loaded ' + state.trace.length + ' events. ' + skipped.join('. ') + '.', 'ok');
  }

  files.forEach((file) => {
    const reader = new FileReader();
    reader.onload = function () {
      const text = String(reader.result);
      const isPem = /\.pem$/i.test(file.name) || /-----BEGIN [A-Z ]*PUBLIC KEY-----/.test(text);
      try {
        if (isPem) {
          verifierPublicKey = text;
        } else if (/\.(json|jsonl|txt)$/i.test(file.name) || text.trim()[0] === '[' || text.trim()[0] === '{') {
          // Could be a verdict.json, a trace, or a wrapper. Try verdict first.
          const t = text.trim();
          let parsedAsVerdict = null;
          if (t[0] === '{') {
            try {
              const obj = JSON.parse(t);
              if (isVerdictObject(obj)) parsedAsVerdict = obj;
            } catch (_) {
              // not a single JSON object (e.g. JSONL) — fall through to trace parse
            }
          }
          if (parsedAsVerdict) {
            verdict = parsedAsVerdict;
          } else {
            const parsed = parseTraceText(text);
            events = parsed.events;
            if (parsed.claims) claims = parsed.claims;
            if (parsed.verifierPublicKey) verifierPublicKey = parsed.verifierPublicKey;
          }
        } else if (looksLikePublicKey(text)) {
          verifierPublicKey = text;
        } else {
          // Last resort: try to parse as a trace anyway.
          const parsed = parseTraceText(text);
          events = parsed.events;
          if (parsed.claims) claims = parsed.claims;
          if (parsed.verifierPublicKey) verifierPublicKey = parsed.verifierPublicKey;
        }
        names.push(file.name);
      } catch (err) {
        errors.push('"' + file.name + '": ' + err.message);
      }
      pending -= 1;
      done();
    };
    reader.onerror = function () {
      errors.push('could not read "' + file.name + '"');
      pending -= 1;
      done();
    };
    reader.readAsText(file);
  });
}

function exportTrace() {
  // Export the full run bundle, including the out-of-band verifier public key
  // so a downstream panel can re-verify the signature.
  const bundle = {
    runId: deriveRunHeader(state.trace).runId,
    events: state.trace,
    claims: state.claims,
    verifierPublicKey: state.verifierPublicKey || undefined,
  };
  const blob = new Blob([JSON.stringify(bundle, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = el('a');
  a.href = url;
  a.download = 'glyphspek-bundle-' + (deriveRunHeader(state.trace).runId || 'run').slice(0, 8) + '.json';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

