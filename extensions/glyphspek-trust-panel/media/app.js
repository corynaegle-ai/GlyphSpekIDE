function renderVerifierVerdict() {
  const root = document.getElementById('verifier-verdict-body');
  const card = document.getElementById('verifier-verdict-card');
  clear(root);
  const v = deriveVerdict(state.trace);

  if (!v) {
    if (card) card.classList.remove('verdict-untrusted');
    root.appendChild(el('p', { className: 'empty', text: 'No verifier verdict in this trace. The run is unverified.' }));
    return;
  }

  // GATE (additive, defense-in-depth). A verdict is AUTHORITATIVE only when ALL
  // of these hold:
  //   (1) the Ed25519 signature over the verdict object VERIFIES, AND
  //   (2) the loaded trace's hash chain is intact (verifyChainBrowser.ok), AND
  //   (3) the recomputed trace root === verdict.traceRootHash.
  // A valid signature with a broken chain OR a non-matching root means the
  // verdict is cryptographically authentic but is NOT bound to the trace shown
  // here — the EVIDENCE BUNDLE is untrusted/inconsistent, so we de-authoritate.
  const res = state.sigResult;
  const sigVerified = !!res && res.status === 'verified';          // any key verified
  const tier = sigVerified ? res.tier : null;                       // 'product'|'demo'|'untrusted-key'|null
  const sigVerifiedByProduct = sigVerified && tier === 'product';   // out-of-band PRODUCT key verified
  const sigVerifiedByDemo     = sigVerified && tier === 'demo';     // built-in DEMO key verified
  // A pinned trust root (product OR demo) matched — eligible for SOME verified
  // state; the gate below still distinguishes full vs demo authority by tier.
  const sigVerifiedByTrusted = sigVerifiedByProduct || sigVerifiedByDemo;
  const sigValidUntrustedKey  = sigVerified && tier === 'untrusted-key'; // only bundle key verified
  const chain = state.chainResult;
  // Treat the bundle integrity as satisfied only once the async chain check has
  // resolved AND both legs pass. While pending (chain === null) we are NOT yet
  // authoritative.
  const bundleConsistent = !!chain && chain.chainOk === true && chain.rootMatches === true;

  // FULL (PRODUCT) AUTHORITATIVE requires a PRODUCT-tier signature AND a
  // consistent bundle. The DEMO tier can NEVER reach this state.
  const verified = sigVerifiedByProduct && bundleConsistent;

  // DEMO-AUTHORITATIVE: a DEMO-tier signature AND a consistent bundle. A real,
  // honest "the demo works" state — verified against the built-in DEMO trust
  // root, but explicitly NOT a production verifier.
  const demoAuthoritative = sigVerifiedByDemo && bundleConsistent;

  // Signature valid (by a trusted product OR demo key) but the bundle doesn't
  // back it — the existing "inconsistent" mode. An untrusted-key signature is
  // already non-authoritative regardless of chain.
  const sigValidButInconsistent = sigVerifiedByTrusted && !!chain && !bundleConsistent;

  // De-authoritative styling on the whole panel when not FULLY authoritative.
  // The demo-authoritative state gets its own distinct (non-product) treatment.
  if (card) {
    card.classList.toggle('verdict-untrusted', !verified && !demoAuthoritative);
    card.classList.toggle('verdict-demo-authoritative', demoAuthoritative); // NEW
    card.classList.toggle('verdict-inconsistent', sigValidButInconsistent);
    card.classList.toggle('verdict-untrusted-key', sigValidUntrustedKey);
  }

  // Signature badge FIRST — it is the gate, so it leads. Pass the resolved tier
  // and full-authoritative boolean so the badge can show product vs demo vs
  // untrusted-key honestly, never collapsing demo into product authority.
  root.appendChild(buildSigBadge(v.signature, res, verified, demoAuthoritative));

  // Trace-binding badge SECOND — the evidence-bundle integrity gate. Only shown
  // once the signature verified BY A TRUSTED (product OR demo) KEY (otherwise the
  // signature badge already tells the whole story; we never show "evidence
  // bundle verified" for a signature produced by an untrusted bundle key).
  if (sigVerifiedByTrusted) {
    root.appendChild(buildChainBadge(chain, verified || demoAuthoritative));
  }

  // Overall verdict banner.
  if (verified) {
    const banner = el('div', { className: 'verdict-banner verdict-' + v.overallVerdict });
    banner.appendChild(el('span', { className: 'verdict-label', text: 'OVERALL VERDICT' }));
    banner.appendChild(el('span', { className: 'verdict-value', text: (v.overallVerdict || 'unknown').toUpperCase() }));
    root.appendChild(banner);
  } else if (demoAuthoritative) {
    // DEMO-AUTHORITATIVE: chain + root verified against the built-in DEMO trust
    // root. Honest "the demo works" state, but a clearly distinct, NON-product
    // banner — it MUST NOT be mistaken for full production AUTHORITATIVE.
    const banner = el('div', { className: 'verdict-banner verdict-demo-authoritative-banner' });
    banner.appendChild(el('span', { className: 'verdict-label', text: 'DEMO-AUTHORITATIVE' }));
    banner.appendChild(
      el('span', {
        className: 'verdict-value',
        text:
          'verified against the built-in DEMO trust root, NOT a production verifier — claims "' +
          (v.overallVerdict || 'unknown').toUpperCase() + '"',
      }),
    );
    root.appendChild(banner);
  } else if (sigValidButInconsistent) {
    // Signature is cryptographically valid (trusted key), but the bundle it
    // signed is not the trace shown here. Do NOT present pass/fail as proven.
    const banner = el('div', { className: 'verdict-banner verdict-inconsistent-banner' });
    banner.appendChild(el('span', { className: 'verdict-label', text: 'VERDICT — INCONSISTENT BUNDLE' }));
    banner.appendChild(
      el('span', {
        className: 'verdict-value',
        text: '(signature valid, but NOT bound to this trace)',
      }),
    );
    root.appendChild(banner);
  } else if (sigValidUntrustedKey) {                                       // NEW
    // Signature is cryptographically valid, but ONLY against a key supplied by
    // the (untrusted) bundle — never a pinned out-of-band verifier key.
    const banner = el('div', { className: 'verdict-banner verdict-untrusted-key-banner' });
    banner.appendChild(el('span', { className: 'verdict-label', text: 'VERDICT — UNTRUSTED KEY' }));
    banner.appendChild(
      el('span', {
        className: 'verdict-value',
        text: '(signature valid, but signed by an UNTRUSTED key supplied by the bundle)',
      }),
    );
    root.appendChild(banner);
  } else {
    const banner = el('div', { className: 'verdict-banner verdict-untrusted-banner' });
    banner.appendChild(el('span', { className: 'verdict-label', text: 'VERDICT — UNTRUSTED' }));
    banner.appendChild(
      el('span', {
        className: 'verdict-value',
        text: '(claims "' + (v.overallVerdict || 'unknown').toUpperCase() + '")',
      }),
    );
    root.appendChild(banner);
  }

  // Per-check results.
  const checksWrap = el('div', { className: 'field' });
  checksWrap.appendChild(el('div', { className: 'field-label', text: 'Checks (sourced from Policy.verify — actor cannot narrow)' }));
  const tbl = el('table', { className: 'mini-table check-table' });
  for (const ck of v.checks || []) {
    const tr = el('tr');
    tr.appendChild(el('td', { text: ck.name }));
    const cmdTd = el('td');
    cmdTd.appendChild(el('code', { text: argvToString(ck.command) }));
    tr.appendChild(cmdTd);
    const statTd = el('td');
    statTd.appendChild(el('span', { className: 'verdict-pill check-' + ck.status, text: ck.status }));
    tr.appendChild(statTd);
    tbl.appendChild(tr);
  }
  checksWrap.appendChild(tbl);
  root.appendChild(checksWrap);

  // Trace root hash binding.
  const rootHash = el('div', { className: 'field' });
  rootHash.appendChild(el('div', { className: 'field-label', text: 'Bound trace_root_hash' }));
  rootHash.appendChild(el('code', { className: 'field-value mono', text: v.traceRootHash || '(none)' }));
  root.appendChild(rootHash);
}

/**
 * Build the signature gate badge. `verified === true` is the ONLY state that
 * presents the verdict as full (PRODUCT) authoritative. `demoAuthoritative`
 * gets a clearly distinct DEMO badge — verified against the built-in demo trust
 * root, never presented as production authority. Every other state is shown as
 * de-authoritative and explicitly NOT verified (never silently "verified").
 */
function buildSigBadge(sig, res, verified, demoAuthoritative) {
  const status = res ? res.status : sig ? 'pending' : 'no-signature';
  const detail = res ? res.detail : '';

  // Signature cryptographically valid, but ONLY for a key SUPPLIED BY THE BUNDLE
  // (tier 'untrusted-key'). Honest, distinct from "no signature" and from a
  // genuine verify failure — its own caution badge, never authoritative.
  if (res && res.status === 'verified' && res.tier === 'untrusted-key') {
    const badge = el('div', { className: 'sig-badge sig-untrusted-key' });
    badge.appendChild(el('span', { className: 'sig-x', text: '⚠' }));
    const txt = el('span', {
      text: '⚠ signature NOT trusted — valid only for a key SUPPLIED BY THE BUNDLE, not a pinned out-of-band verifier key',
    });
    if (res.detail) txt.title = res.detail;
    badge.appendChild(txt);
    return badge;
  }

  // DEMO tier verified AND bundle-consistent: a real verified state, but against
  // the built-in DEMO trust root only. Distinct badge — NEVER the green product
  // "authoritative" badge.
  if (demoAuthoritative) {
    const badge = el('div', { className: 'sig-badge sig-demo-authoritative' });
    badge.appendChild(el('span', { className: 'sig-check', text: '✓' }));
    const txt = el('span');
    txt.appendChild(el('strong', { text: 'signature verified ✓ (DEMO trust root)' }));
    txt.appendChild(
      el('span', {
        text:
          ' — DEMO-AUTHORITATIVE. Ed25519, verified in-browser against the BUILT-IN DEMO verifier key, NOT a production trust root. Provision an out-of-band key (GLYPHSPEK_TRUSTED_VERIFIER_KEYS) for full authority.',
      }),
    );
    // keyId is DISPLAY-ONLY (never the basis of trust): shown as a title label.
    if (sig) txt.title = 'keyId (label only, not trusted): ' + sig.keyId + '\n' + sig.value;
    badge.appendChild(txt);
    return badge;
  }

  const badge = el('div', { className: 'sig-badge ' + (verified ? 'sig-present' : 'sig-failed') });

  if (verified) {
    badge.appendChild(el('span', { className: 'sig-check', text: '✓' }));
    const txt = el('span');
    txt.appendChild(el('strong', { text: 'signature verified ✓' }));
    txt.appendChild(
      el('span', {
        text:
          ' — authoritative. Ed25519, verified in-browser against a TRUSTED (out-of-band) PRODUCT verifier key over canonical (verdict, traceRootHash).',
      }),
    );
    // keyId is DISPLAY-ONLY (never the basis of trust): shown as a title label.
    if (sig) txt.title = 'keyId (label only, not trusted): ' + sig.keyId + '\n' + sig.value;
    badge.appendChild(txt);
    return badge;
  }

  // Not verified — choose an exact, honest message per failure mode.
  badge.appendChild(el('span', { className: 'sig-x', text: '⚠' }));
  let message;
  switch (status) {
    case 'pending':
      message = 'verifying signature…';
      break;
    case 'no-signature':
      message = '⚠ signature NOT verified — verdict shown as UNTRUSTED (no signature present)';
      break;
    case 'no-key':
      message =
        '⚠ signature NOT verified — verdict shown as UNTRUSTED (no verifier public key loaded with the bundle)';
      break;
    case 'unsupported':
      message =
        '⚠ signature NOT verified — verdict shown as UNTRUSTED (' +
        (detail || 'Web Crypto Ed25519 unsupported') +
        ')';
      break;
    case 'failed':
    case 'error':
    default:
      message = '⚠ signature NOT verified — verdict shown as UNTRUSTED';
      break;
  }
  const txt = el('span', { text: message });
  if (detail && status !== 'unsupported') txt.title = detail;
  badge.appendChild(txt);
  return badge;
}

/**
 * Build the trace-binding (evidence-bundle integrity) badge. Shown only after
 * the signature verified. `bundleConsistent === true` means the chain is intact
 * AND the recomputed root matches verdict.traceRootHash — only then is the
 * verdict authoritative. On a MISMATCH we show the recomputed-root vs
 * verdict-root so the inconsistency is visible (the finding's requirement).
 */
function buildChainBadge(chain, bundleConsistent) {
  // Pending: chain check has not resolved yet.
  if (!chain) {
    const badge = el('div', { className: 'sig-badge sig-failed' });
    badge.appendChild(el('span', { className: 'sig-x', text: '…' }));
    badge.appendChild(el('span', { text: 'verifying trace chain + root binding…' }));
    return badge;
  }

  if (bundleConsistent) {
    const badge = el('div', { className: 'sig-badge sig-present' });
    badge.appendChild(el('span', { className: 'sig-check', text: '✓' }));
    const txt = el('span');
    txt.appendChild(el('strong', { text: 'evidence bundle verified ✓' }));
    txt.appendChild(
      el('span', {
        text:
          ' — hash chain intact and trace root matches the signed verdict ' +
          '(' + shortHash(chain.recomputedRoot) + ').',
      }),
    );
    badge.appendChild(txt);
    return badge;
  }

  // Inconsistent: signature was valid but the bundle does not back it.
  const badge = el('div', { className: 'sig-badge sig-failed' });
  badge.appendChild(el('span', { className: 'sig-x', text: '⚠' }));
  const txt = el('span');
  if (!chain.chainOk) {
    txt.appendChild(el('strong', { text: '⚠ evidence bundle UNTRUSTED — trace chain BROKEN' }));
    const where =
      typeof chain.brokenIndex === 'number'
        ? ' (first broken at event #' + chain.brokenIndex + ')'
        : '';
    txt.appendChild(
      el('span', {
        text:
          where +
          '. The signature is cryptographically valid, but the loaded trace ' +
          'fails hash-chain verification, so the verdict is NOT bound to it.',
      }),
    );
  } else {
    txt.appendChild(el('strong', { text: '⚠ evidence bundle INCONSISTENT — trace root does NOT match verdict' }));
    txt.appendChild(
      el('span', {
        text:
          '. The signature is cryptographically valid over the verdict, but the ' +
          'loaded trace is not the one it committed to (root mismatch).',
      }),
    );
  }
  badge.appendChild(txt);

  // Always surface recomputed-root vs verdict-root on mismatch.
  const cmp = el('div', { className: 'chain-root-compare' });
  const reLine = el('div', { className: 'field' });
  reLine.appendChild(el('span', { className: 'meta-label', text: 'recomputed trace root: ' }));
  reLine.appendChild(el('code', { className: 'mono', text: chain.recomputedRoot || '(none)' }));
  const vdLine = el('div', { className: 'field' });
  vdLine.appendChild(el('span', { className: 'meta-label', text: 'verdict.traceRootHash: ' }));
  vdLine.appendChild(el('code', { className: 'mono', text: chain.verdictRoot || '(none)' }));
  cmp.appendChild(reLine);
  cmp.appendChild(vdLine);
  badge.appendChild(cmp);

  return badge;
}

function escapeHtml(s) {
  return String(s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

