function deriveRunHeader(trace) {
  const created = trace.find((e) => e.type === 'run_created');
  const runId = created ? (created.payload && created.payload.runId) || created.runId : trace[0] && trace[0].runId;
  const stateChanges = trace.filter((e) => e.type === 'run_state_changed');
  const last = stateChanges[stateChanges.length - 1];
  const status = last ? last.payload.to : created ? 'created' : 'unknown';
  const modelCall = trace.find((e) => e.type === 'model_call');
  const model = modelCall ? modelCall.payload.model : null;
  const tokens = trace
    .filter((e) => e.type === 'model_call')
    .reduce(
      (acc, e) => {
        acc.input += e.payload.inputTokens || 0;
        acc.output += e.payload.outputTokens || 0;
        return acc;
      },
      { input: 0, output: 0 },
    );
  const runDir = created && created.payload ? created.payload.runDir : null;
  return { runId, status, model, tokens, runDir };
}

function deriveVerdict(trace) {
  // A standalone verdict.json (e.g. the capstone bundle) takes precedence over
  // a verifier_verdict event embedded in the trace.
  if (state.standaloneVerdict) return state.standaloneVerdict;
  const evt = trace.find((e) => e.type === 'verifier_verdict');
  return evt ? evt.payload : null;
}

/** True if `obj` is a standalone VerifierVerdict (verdict.json), not a trace. */
function isVerdictObject(obj) {
  return (
    obj &&
    typeof obj === 'object' &&
    !Array.isArray(obj) &&
    Array.isArray(obj.checks) &&
    typeof obj.traceRootHash === 'string' &&
    !Array.isArray(obj.events)
  );
}

function deriveCommands(trace) {
  // A command "ran" if there is a tool_start/tool_end for it. We pair by argv.
  const out = [];
  for (const e of trace) {
    if (e.type === 'tool_end' && e.payload && e.payload.tool === 'command') {
      out.push({
        argv: e.payload.argv || [],
        exitCode: e.payload.exitCode,
        durationMs: e.payload.durationMs,
      });
    }
  }
  return out;
}

function deriveNetwork(trace) {
  const out = [];
  for (const e of trace) {
    if (e.type === 'policy_decision' && e.payload && e.payload.tool === 'network') {
      // F1: an observe-only egress is OBSERVED on the bypassable soft plane, NOT a
      // policy allow — surface it distinctly so it never reads as "policy: allowed".
      const obs = e.payload.enforcement === 'observe-only';
      out.push({
        destination: e.payload.destination || e.payload.requestedCapability,
        decision: e.payload.decision,
        blocked: obs ? false : !!e.payload.blocked,
        observeOnly: obs,
      });
    }
  }
  return out;
}

function derivePolicyDecisions(trace) {
  return trace
    .filter((e) => e.type === 'policy_decision')
    .map((e) => {
      const obs = e.payload.enforcement === 'observe-only';
      return {
        tool: e.payload.tool,
        requestedCapability: e.payload.requestedCapability,
        decision: e.payload.decision,
        blocked: obs ? false : !!e.payload.blocked,
        rule: e.payload.rule,
        provenanceLabel: e.payload.provenanceLabel,
        enforcement: obs ? 'observe-only' : undefined,
      };
    });
}

