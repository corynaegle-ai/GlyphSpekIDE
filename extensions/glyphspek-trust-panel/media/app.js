/**
 * Demo: flip one byte of the signed verdict so the signature NO LONGER matches,
 * proving the gate. Deep-clones the real sample, mutates overallVerdict
 * (pass<->fail), and reloads — verification will fail and the badge flips to
 * "NOT verified".
 */
function tamperSample() {
  if (!REAL_SAMPLE_BUNDLE) {
    setStatus('Tamper demo needs the embedded signed sample (sample-bundle.js).', 'err');
    return;
  }
  const events = JSON.parse(JSON.stringify(REAL_SAMPLE_BUNDLE.events));
  // Tamper the SIGNED content (not the signature): the verdict the actor would
  // love to forge. The signature was computed over the original, so it breaks.
  // The default sample carries a DETACHED verdict; older mock-style samples carry
  // an in-trace verifier_verdict event. Tamper whichever is present.
  let verdict = REAL_SAMPLE_BUNDLE.verdict
    ? JSON.parse(JSON.stringify(REAL_SAMPLE_BUNDLE.verdict))
    : null;
  if (verdict) {
    verdict.overallVerdict = verdict.overallVerdict === 'pass' ? 'fail' : 'pass';
  } else {
    const verdictEvt = events.find((e) => e.type === 'verifier_verdict');
    if (verdictEvt && verdictEvt.payload) {
      verdictEvt.payload.overallVerdict =
        verdictEvt.payload.overallVerdict === 'pass' ? 'fail' : 'pass';
    }
  }
  loadBundle(
    {
      events,
      claims: REAL_SAMPLE_BUNDLE.claims || null,
      verifierPublicKey: REAL_SAMPLE_BUNDLE.verifierPublicKey || null,
      verdict,
    },
    'TAMPERED sample (one byte flipped — should NOT verify)',
  );
}

function setStatus(msg, kind) {
  const node = document.getElementById('load-status');
  if (!node) return;
  node.textContent = msg;
  node.className = 'load-status ' + (kind || '');
}

/* ================================================================== *
 * VS Code / Code-OSS WEBVIEW HOST BRIDGE.
 *
 * This file is the same trust surface used by the standalone prototype, hosted
 * verbatim inside a webview by the GlyphSpek extension. Browsers block file://
 * fetch and a webview's CSP forbids the native file picker reaching disk, so
 * the EXTENSION HOST reads a run-bundle directory (trace.jsonl + verdict.json +
 * verifier-public-key.pem [+ actor-claims.json]) with node:fs and posts the
 * RAW file contents here. The webview then parses, renders, and VERIFIES the
 * Ed25519 signature in-browser exactly as the prototype does — the host never
 * tells the webview whether a verdict is trustworthy; the gate stays in the
 * webview where Web Crypto runs. When not hosted in a webview (acquireVsCodeApi
 * absent) this is a no-op and the page behaves like the plain prototype.
 * ================================================================== */

const vscodeApi =
  typeof acquireVsCodeApi === 'function' ? acquireVsCodeApi() : null;

/**
 * Normalize the capstone-style actor-claims.json shape
 * ({ plan, summary, claimedFilesChanged, claimedChecks:[{name, claimedStatus}] })
 * to the shape the Actor-claims renderer expects
 * ({ plan, summary, claimedChangedFiles, claimedChecks:[{name, claim}] }).
 * Already-normalized claims pass through unchanged. Claims are NEVER merged
 * with a verdict — they remain the actor's non-authoritative self-report.
 */
function normalizeClaims(raw) {
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return null;
  const out = {
    plan: raw.plan,
    summary: raw.summary,
    claimedChangedFiles: raw.claimedChangedFiles || raw.claimedFilesChanged || null,
  };
  const checks = raw.claimedChecks;
  if (Array.isArray(checks)) {
    out.claimedChecks = checks.map((c) => ({
      name: c && c.name,
      claim: c && (c.claim != null ? c.claim : c.claimedStatus),
    }));
  }
  return out;
}

/**
 * Ingest run-bundle files posted by the extension host. Each entry is
 * { name, text } (the raw on-disk contents). Reuses the exact same parsing /
 * classification logic as the drag-drop path so behavior is identical, then
 * loads the assembled bundle through loadBundle (which triggers in-browser
 * signature verification). The verifier public key is taken ONLY from a .pem /
 * PUBLIC KEY file (out-of-band), never trusted from inside the trace.
 */
function ingestPostedFiles(files) {
  const list = Array.isArray(files) ? files : [];
  if (!list.length) {
    setStatus('No files in the selected run bundle.', 'err');
    return;
  }

  let events = null;
  let claims = null;
  let verifierPublicKey = null;
  let verdict = null;
  const names = [];
  const errors = [];

  for (const file of list) {
    const name = (file && file.name) || 'file';
    const text = file && typeof file.text === 'string' ? file.text : '';
    const isPem = /\.pem$/i.test(name) || /-----BEGIN [A-Z ]*PUBLIC KEY-----/.test(text);
    try {
      if (isPem) {
        verifierPublicKey = text;
      } else if (/actor-claims\.json$/i.test(name)) {
        // Standalone capstone-style actor claims file.
        const parsed = normalizeClaims(JSON.parse(text.trim()));
        if (parsed) claims = parsed;
      } else if (/\.(json|jsonl|txt)$/i.test(name) || text.trim()[0] === '[' || text.trim()[0] === '{') {
        const t = text.trim();
        let parsedAsVerdict = null;
        if (t[0] === '{') {
          try {
            const obj = JSON.parse(t);
            if (isVerdictObject(obj)) parsedAsVerdict = obj;
          } catch (_) {
            // not a single JSON object (e.g. JSONL) — fall through to trace parse
          }
        }
        if (parsedAsVerdict) {
          verdict = parsedAsVerdict;
        } else {
          const parsed = parseTraceText(text);
          events = parsed.events;
          if (parsed.claims) claims = parsed.claims;
          if (parsed.verifierPublicKey) verifierPublicKey = parsed.verifierPublicKey;
        }
      } else if (looksLikePublicKey(text)) {
        verifierPublicKey = text;
      } else {
        const parsed = parseTraceText(text);
        events = parsed.events;
        if (parsed.claims) claims = parsed.claims;
        if (parsed.verifierPublicKey) verifierPublicKey = parsed.verifierPublicKey;
      }
      names.push(name);
    } catch (err) {
      errors.push('"' + name + '": ' + (err && err.message ? err.message : String(err)));
    }
  }

  if (!events && !verdict) {
    setStatus(
      'No trace or verdict found in ' +
        (names.join(', ') || 'the selected run bundle') +
        (errors.length ? '. ' + errors.join('; ') : '. Provide a trace .json/.jsonl or verdict.json.'),
      'err',
    );
    return;
  }
  loadBundle({ events: events || [], claims, verifierPublicKey, verdict }, names.join(' + '));
}

/**
 * The trusted-run KIND the host last asked us to offer (sweep-20 High #3), if any.
 * Posting `startTrustedRun` with this kind is the first-party operator gesture that
 * the host turns into a product-trusted run. A third-party extension cannot reach
 * this state because it cannot post into our webview.
 */
let pendingTrustedRunKind = null;

/** Show/hide the first-party "Start run" affordance for a given run kind. */
function showTrustedRunOffer(kind) {
  pendingTrustedRunKind = kind || null;
  const offer = document.getElementById('trusted-run-offer');
  if (offer) offer.hidden = !pendingTrustedRunKind;
}

/** Wire the host→webview message channel. Idempotent / safe if no host. */
function wireHostBridge() {
  window.addEventListener('message', function (event) {
    const msg = event && event.data;
    if (!msg || typeof msg !== 'object') return;
    if (msg.type === 'loadBundleFiles') {
      ingestPostedFiles(msg.files);
    } else if (msg.type === 'offerTrustedRun') {
      // A GlyphSpek command asked to start a trusted run. Surface the first-party
      // "Start run" button; the operator clicking it is the gesture that the host
      // (and ONLY a webview message) turns into a product-trusted run.
      showTrustedRunOffer(msg.kind);
    }
  });
  // Tell the host the panel is ready (so a load requested before the webview
  // finished booting can be replayed).
  if (vscodeApi) {
    try {
      vscodeApi.postMessage({ type: 'ready' });
    } catch (_) {
      /* no-op */
    }
  }
}

