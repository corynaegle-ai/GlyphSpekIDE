/*
 * GlyphSpek Trust Panel prototype (W1-19 / W1-27).
 *
 * Vanilla JS, zero dependencies, no build step. Open index.html directly.
 *
 * LOAD-BEARING PRINCIPLE
 * ----------------------
 * The agent's CLAIMS (what the actor says it did) and the independent
 * VERIFIER's VERDICT (an authoritative, signed VerifierVerdict) are NEVER
 * conflated. They render as visually distinct sections with distinct labels,
 * colors, and framing. An actor's self-reported success is not a verdict.
 *
 * Data shapes mirror spikes/p0-contracts:
 *   - TraceEvent envelope: { v, runId, seq, ts, type, prevHash, hash, payload }
 *   - TraceEventType: run_created | run_state_changed | policy_decision |
 *       tool_start | tool_end | redaction | prompt | model_call | verifier_verdict
 *   - PolicyDecision (7): allow | deny | ask | force_ask |
 *       allow_with_redaction | sandbox_only | read_only
 *   - VerifierVerdict: { checks[{name,command,status}], overallVerdict,
 *       traceRootHash, signature{alg,value,keyId} }
 *
 * SIGNATURE BEFORE DISPLAY (charter requirement)
 * ----------------------------------------------
 * The verifier verdict is shown as AUTHORITATIVE only after its Ed25519
 * detached signature is VERIFIED in-browser with Web Crypto. The scheme is
 * reproduced byte-for-byte from spikes/p0-contracts/SIGNING.md and
 * spikes/p0-verifier/signing.ts: the signed message is the UTF-8 bytes of
 *   canonicalJson({ traceRootHash, verdict-without-signature })
 * and the signature (base64) is checked against the verifier's SPKI public
 * key, resolved out-of-band (loaded with the bundle, NOT trusted from the
 * actor). If verification fails — or the browser lacks Web Crypto Ed25519
 * support — the verdict is shown as UNTRUSTED, never silently "verified".
 *
 * The DEFAULT sample (sample-bundle.js, generated by tools/generate-sample.mjs)
 * carries a REAL signature and verifies on open. Trace-chain hashes are
 * realistic-looking hex PLACEHOLDERS, not real chain hashes; the SIGNATURE is
 * real.
 */

